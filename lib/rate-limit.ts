// Simple fixed-window limiter. Good enough for a single Vercel/Node instance.
// If you deploy multiple instances (or serverless with many cold starts),
// each instance has its own memory — replace this with Upstash Redis
// (`@upstash/ratelimit`) so the count is shared.

const hits = new Map<string, { count: number; resetAt: number }>();

export function rateLimit(key: string, limit: number, windowMs: number) {
  const now = Date.now();
  const entry = hits.get(key);

  if (!entry || entry.resetAt < now) {
    hits.set(key, { count: 1, resetAt: now + windowMs });
    return { allowed: true, remaining: limit - 1 };
  }

  if (entry.count >= limit) {
    return { allowed: false, remaining: 0 };
  }

  entry.count += 1;
  return { allowed: true, remaining: limit - entry.count };
}
